create or replace function public.cancel_my_order(
  p_order_id bigint,
  p_refund_destination text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_order public.orders%rowtype;
  v_external_refund numeric(10, 2) := 0;
  v_wallet_credit numeric(10, 2) := 0;
  v_result text := 'cancelled';
begin
  if v_user_id is null then
    raise exception 'Inicia sesión para cancelar el pedido.';
  end if;

  if p_refund_destination is null
     or p_refund_destination not in ('mercadopago', 'store_credit', 'manual') then
    raise exception 'La opción de reembolso no es válida.';
  end if;

  select *
  into v_order
  from public.orders
  where id = p_order_id
    and user_id = v_user_id
  for update;

  if not found then
    raise exception 'No se encontró el pedido.';
  end if;

  if v_order.status = 'cancelled'
     and v_order.payment_status = 'refund_pending' then
    if v_order.refund_destination is distinct from p_refund_destination then
      raise exception 'El reembolso de este pedido ya está en proceso.';
    end if;

    if v_order.refund_destination = 'mercadopago' then
      return jsonb_build_object(
        'result', 'refund_pending',
        'provider_order_id', v_order.provider_order_id,
        'order_id', v_order.id
      );
    end if;

    return jsonb_build_object(
      'result', 'manual_refund_pending',
      'order_id', v_order.id
    );
  end if;

  if v_order.status = 'cancelled' then
    return jsonb_build_object('result', 'already_cancelled');
  end if;

  if v_order.status not in ('pending_payment', 'paid') then
    raise exception 'Este pedido ya no se puede cancelar.';
  end if;

  if v_order.fulfillment_status not in ('pending', 'preparing') then
    raise exception 'El pedido ya está listo o salió a entrega y no se puede cancelar.';
  end if;

  if v_order.fulfillment_status = 'preparing'
     and (
       not exists (
         select 1
         from public.order_items
         where order_id = p_order_id
       )
       or exists (
         select 1
         from public.order_items as item
         where item.order_id = p_order_id
           and item.cancellation_recoverable is distinct from true
       )
     ) then
    raise exception 'Solo se cancela durante preparación si todos los productos son recuperables.';
  end if;

  if v_order.status = 'pending_payment' then
    if p_refund_destination = 'manual' then
      raise exception 'Este pedido aún no tiene un pago en efectivo confirmado.';
    end if;

    if p_refund_destination = 'store_credit'
       and v_order.payment_method = 'online' then
      raise exception 'El pago en línea aún no está aprobado; no se puede emitir saldo.';
    end if;

    v_wallet_credit := v_order.wallet_amount;
  else
    if v_order.payment_status <> 'approved' then
      raise exception 'El pago del pedido no está confirmado.';
    end if;

    if v_order.payment_provider = 'cash' then
      if p_refund_destination <> 'manual' then
        raise exception 'El reembolso de efectivo cobrado debe gestionarlo el dueño.';
      end if;
      v_wallet_credit := v_order.wallet_amount;
      v_result := 'manual_refund_pending';
    elsif v_order.payment_provider in ('mercadopago', 'wallet') then
      if v_order.payment_provider = 'wallet'
         and p_refund_destination <> 'store_credit' then
        raise exception 'Un pedido pagado con saldo solo puede devolverse al saldo de tienda.';
      end if;

      if p_refund_destination = 'store_credit' then
        v_wallet_credit := v_order.total;
        v_result := 'credited';
      elsif p_refund_destination = 'mercadopago' then
        v_wallet_credit := v_order.wallet_amount;
        v_external_refund := v_order.total - v_order.wallet_amount;
        if v_external_refund > 0 then
          if v_order.payment_provider <> 'mercadopago'
             or v_order.provider_order_id is null then
            raise exception 'No se encontró el pago de Mercado Pago para devolver.';
          end if;
          v_result := 'refund_pending';
        else
          v_result := 'credited';
        end if;
      else
        raise exception 'Elige cómo recibir el reembolso.';
      end if;
    else
      raise exception 'No se puede determinar cómo se pagó este pedido.';
    end if;

    update public.products as product
    set stock = product.stock + detail.quantity
    from public.order_items as detail
    where detail.order_id = p_order_id
      and detail.product_id = product.id;
  end if;

  if v_wallet_credit > 0 then
    insert into public.customer_wallets (user_id, balance)
    values (v_user_id, v_wallet_credit)
    on conflict (user_id) do update
      set balance = public.customer_wallets.balance + excluded.balance,
          updated_at = now();

    insert into public.wallet_transactions (
      user_id,
      order_id,
      transaction_type,
      amount
    )
    values (
      v_user_id,
      p_order_id,
      case
        when v_result = 'credited' then 'cancellation_credit'
        else 'cancellation_wallet_restore'
      end,
      v_wallet_credit
    );
  end if;

  update public.orders
  set status = 'cancelled',
      fulfillment_status = 'cancelled',
      payment_status = case
        when v_result in ('refund_pending', 'manual_refund_pending')
          then 'refund_pending'
        when v_result = 'credited' then 'credited'
        else 'cancelled'
      end,
      refund_destination = p_refund_destination,
      cancelled_at = now()
  where id = p_order_id;

  delete from public.order_stock_reservations
  where order_id = p_order_id;

  return jsonb_build_object(
    'result', v_result,
    'order_id', p_order_id,
    'provider_order_id', v_order.provider_order_id,
    'external_refund_amount', v_external_refund,
    'wallet_credit', v_wallet_credit
  );
end;
$$;

