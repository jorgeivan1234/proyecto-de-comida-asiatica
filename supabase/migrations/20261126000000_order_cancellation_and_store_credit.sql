    if exists (
      select 1
      from public.orders
      where id = p_order_id
        and status in ('cancelled', 'refunded')
        and payment_provider = 'mercadopago'
        and refund_destination = 'mercadopago'
        and payment_status in ('refund_requested', 'refunded')
    ) then
      return;
    end if;

    raise exception 'El reembolso no está pendiente para este pedido.';
  end if;
end;
$$;

