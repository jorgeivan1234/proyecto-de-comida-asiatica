create or replace function public.snapshot_order_item_recoverability()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.product_id is null then
    new.cancellation_recoverable := false;
  else
    select product.cancellation_recoverable
    into new.cancellation_recoverable
    from public.products as product
    where product.id = new.product_id;

    new.cancellation_recoverable :=
      coalesce(new.cancellation_recoverable, false);
  end if;

  return new;
end;
$$;

