create or replace function public.place_order_with_options(
  p_items jsonb,
  p_fulfillment_method text,
  p_delivery_address text,
  p_payment_method text,
  p_wallet_amount numeric default 0
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_order jsonb;
  v_order_id bigint;
  v_total numeric(10, 2);
  v_wallet_amount numeric(10, 2) := round(coalesce(p_wallet_amount, 0), 2);
  v_amount_due numeric(10, 2);
  v_wallet_balance numeric(10, 2);
  v_final_payment_method text;
  v_final_provider text;
  v_final_status text;
  v_final_payment_status text;
begin
  if v_user_id is null then
    raise exception 'Inicia sesión para crear un pedido.';
  end if;

  if p_payment_method is null
     or p_payment_method not in ('cash', 'online', 'wallet') then
    raise exception 'El método de pago no es válido.';
  end if;

  if p_fulfillment_method is null
     or p_fulfillment_method not in ('pickup', 'delivery') then
    raise exception 'La modalidad de entrega no es válida.';
  end if;

  if p_fulfillment_method = 'delivery'
     and nullif(trim(p_delivery_address), '') is null then
    raise exception 'Escribe la dirección de entrega.';
  end if;

  if v_wallet_amount < 0 then
    raise exception 'El saldo aplicado no es válido.';
  end if;

  v_order := public.place_order(p_items);
  v_order_id := (v_order ->> 'id')::bigint;
  v_total := (v_order ->> 'total')::numeric;

  if v_wallet_amount > v_total then
    raise exception 'El saldo aplicado no puede exceder el total.';
  end if;

  v_amount_due := v_total - v_wallet_amount;

  if v_amount_due > 0 and p_payment_method = 'wallet' then
    raise exception 'El saldo disponible no cubre el pedido completo.';
  end if;

  if v_wallet_amount > 0 then
    insert into public.customer_wallets (user_id)
    values (v_user_id)
    on conflict (user_id) do nothing;

    select balance
    into v_wallet_balance
    from public.customer_wallets
    where user_id = v_user_id
    for update;

    if v_wallet_balance < v_wallet_amount then
      raise exception 'El saldo de tienda ya no es suficiente.';
    end if;

    update public.customer_wallets
    set balance = balance - v_wallet_amount,
        updated_at = now()
    where user_id = v_user_id;

    insert into public.wallet_transactions (
      user_id,
      order_id,
      transaction_type,
      amount
    )
    values (v_user_id, v_order_id, 'order_payment', v_wallet_amount);
  end if;

  if v_amount_due = 0 then
    v_final_payment_method := 'wallet';
    v_final_provider := 'wallet';
    v_final_status := 'paid';
    v_final_payment_status := 'approved';

    update public.products as product
    set stock = product.stock - detail.quantity
    from public.order_items as detail
    where detail.order_id = v_order_id
      and detail.product_id = product.id;

    delete from public.order_stock_reservations
    where order_id = v_order_id;
  else
    v_final_payment_method := p_payment_method;
    v_final_provider := case
      when p_payment_method = 'cash' then 'cash'
      else 'mercadopago'
    end;
    v_final_status := 'pending_payment';
    v_final_payment_status := 'pending';
  end if;

  update public.orders
  set fulfillment_method = p_fulfillment_method,
      delivery_address = case
        when p_fulfillment_method = 'delivery' then trim(p_delivery_address)
        else null
      end,
      payment_provider = v_final_provider,
      payment_method = v_final_payment_method,
      wallet_amount = v_wallet_amount,
      status = v_final_status,
      payment_status = v_final_payment_status,
      paid_at = case when v_amount_due = 0 then now() else null end
  where id = v_order_id
    and user_id = v_user_id;

  return v_order || jsonb_build_object(
    'status', v_final_status,
    'payment_status', v_final_payment_status,
    'payment_method', v_final_payment_method,
    'payment_provider', v_final_provider,
    'wallet_amount', v_wallet_amount,
    'amount_due', v_amount_due
  );
end;
$$;

