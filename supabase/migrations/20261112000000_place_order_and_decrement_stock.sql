create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id),
  status text not null default 'confirmed'
    check (status in ('confirmed', 'paid', 'rejected', 'cancelled')),
  total numeric(10, 2) not null default 0 check (total >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  product_id integer references public.products(id) on delete set null,
  product_name text not null,
  quantity integer not null check (quantity > 0),
  unit_price numeric(10, 2) not null check (unit_price >= 0),
  subtotal numeric(10, 2)
    generated always as (unit_price * quantity) stored
);

alter table public.orders enable row level security;
alter table public.order_items enable row level security;

revoke all on public.orders, public.order_items from anon, authenticated;
grant select on public.orders, public.order_items to authenticated;

drop policy if exists "orders_select_own" on public.orders;
create policy "orders_select_own"
on public.orders for select
to authenticated
using (user_id = (select auth.uid()));

drop policy if exists "order_items_select_own" on public.order_items;
create policy "order_items_select_own"
on public.order_items for select
to authenticated
using (
  exists (
    select 1
    from public.orders
    where orders.id = order_items.order_id
      and orders.user_id = (select auth.uid())
  )
);

create or replace function public.place_order(p_items jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_order_id bigint;
  v_created_at timestamptz;
  v_total numeric(10, 2);
  v_order_items jsonb;
  v_item record;
  v_stock integer;
begin
  if v_user_id is null then
    raise exception 'Inicia sesión para confirmar una compra.';
  end if;

  if p_items is null or jsonb_typeof(p_items) is distinct from 'array' then
    raise exception 'Los productos del pedido no son válidos.';
  end if;

  if jsonb_array_length(p_items) = 0 then
    raise exception 'El carrito está vacío.';
  end if;

  if exists (
    select 1
    from jsonb_to_recordset(p_items) as item(
      product_id integer,
      quantity integer
    )
    where item.product_id is null
       or item.quantity is null
       or item.quantity < 1
  ) then
    raise exception 'El producto o la cantidad del pedido no son válidos.';
  end if;

  for v_item in
    select item.product_id, sum(item.quantity)::integer as quantity
    from jsonb_to_recordset(p_items) as item(
      product_id integer,
      quantity integer
    )
    group by item.product_id
    order by item.product_id
  loop
    select product.stock
    into v_stock
    from public.products as product
    where product.id = v_item.product_id
    for update;

    if not found then
      raise exception 'No se encontró el producto con ID %.',
        v_item.product_id;
    end if;

    if v_stock < v_item.quantity then
      raise exception 'Existencias insuficientes para el producto con ID %.',
        v_item.product_id;
    end if;
  end loop;

  insert into public.orders (user_id, status)
  values (v_user_id, 'confirmed')
  returning id, created_at into v_order_id, v_created_at;

  insert into public.order_items (
    order_id,
    product_id,
    product_name,
    quantity,
    unit_price
  )
  select
    v_order_id,
    product.id,
    product.name,
    item.quantity,
    product.price
  from (
    select item.product_id, sum(item.quantity)::integer as quantity
    from jsonb_to_recordset(p_items) as item(
      product_id integer,
      quantity integer
    )
    group by item.product_id
  ) as item
  join public.products as product on product.id = item.product_id;

  update public.products as product
  set stock = product.stock - detail.quantity
  from public.order_items as detail
  where detail.order_id = v_order_id
    and detail.product_id = product.id;

  select coalesce(sum(detail.subtotal), 0)
  into v_total
  from public.order_items as detail
  where detail.order_id = v_order_id;

  update public.orders
  set total = v_total
  where id = v_order_id;

  select jsonb_agg(
    jsonb_build_object(
      'product_id', detail.product_id,
      'product_name', detail.product_name,
      'quantity', detail.quantity,
      'unit_price', detail.unit_price
    )
    order by detail.id
  )
  into v_order_items
  from public.order_items as detail
  where detail.order_id = v_order_id;

  return jsonb_build_object(
    'id', v_order_id,
    'created_at', v_created_at,
    'status', 'confirmed',
    'total', v_total,
    'items', v_order_items
  );
end;
$$;

revoke all on function public.place_order(jsonb) from public, anon;
grant execute on function public.place_order(jsonb) to authenticated;
